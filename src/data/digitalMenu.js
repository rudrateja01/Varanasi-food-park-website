// Keep track of image selection for each category
const imageIndexes = {};

function getFoodImage(category) {
  let images;

  switch (category) {
    case "Tiffins & Breakfast":
      images = FOOD_IMAGES.breakfast;
      break;

    case "Regular Dosas":
    case "Special Dosas":
    case "Pesarattu Specials":
      images = FOOD_IMAGES.dosa;
      break;

    case "Lunch":
      images = FOOD_IMAGES.lunch;
      break;

    case "Evening Snacks":
      images = FOOD_IMAGES.snacks;
      break;

    case "Evening Special (Non-Veg)":
      images = FOOD_IMAGES.nonVeg;
      break;

    case "Beverages":
      images = FOOD_IMAGES.beverages;
      break;

    case "Extras":
      images = FOOD_IMAGES.extras;
      break;

    case "Sunday Specials":
      images = FOOD_IMAGES.sunday;
      break;

    default:
      images = FOOD_IMAGES.breakfast;
  }

  const currentIndex = imageIndexes[category] || 0;

  imageIndexes[category] = currentIndex + 1;

  return images[currentIndex % images.length];
}

// Replace only image URLs.
// All other food details remain unchanged.
digitalMenu.forEach((item) => {
  item.image = getFoodImage(item.category);
});

